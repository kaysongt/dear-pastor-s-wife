const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'europe-retreat-2027.html'), 'utf8');
const source = fs.readFileSync(path.join(root, 'retreat-2027.js'), 'utf8');
const dom = new JSDOM(html, {runScripts: 'outside-only', url: 'https://dearpastorswife.org/europe-retreat-2027.html'});
// Early-bird pricing closed on 17 October 2026: it must not appear anywhere, even before scripts run.
assert.doesNotMatch(html, /early[ -]?bird|£250|DPWEARLY2027|prefilled_promo_code/i);
assert.doesNotMatch(source, /early[ -]?bird|£250|DPWEARLY2027|prefilled_promo_code/i);
let now = Date.parse('2026-10-20T12:00:00Z');
dom.window.Date.now = () => now;
dom.window.eval(source);
const button = dom.window.document.getElementById('retreat27-checkout');
assert.equal(dom.window.document.querySelectorAll('.retreat27-prices article').length, 1);
assert.match(button.textContent, /£300/);
assert.equal(new URL(button.href).search, '');
assert.match(dom.window.document.getElementById('retreat27-rate-note').textContent, /£300 until 31 October 2026/);
now = Date.parse('2026-10-31T23:59:59Z');
dom.window.document.dispatchEvent(new dom.window.Event('visibilitychange'));
assert.match(button.textContent, /£300/);
now = Date.parse('2026-11-01T00:00:00Z');
dom.window.document.dispatchEvent(new dom.window.Event('visibilitychange'));
assert.match(button.href, /^mailto:/);
assert.doesNotMatch(html, /pic-time|pricing review|UK team|Interim rate|Later registration/);
assert.equal(dom.window.document.querySelector('form').id, 'stayInformedForm');
assert.doesNotMatch(html, /Online payment is not open/);
dom.window.close();
console.log('2027 registration: early bird closed, £300 advance rate, November cutoff and mailing-list separation passed.');
