const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'europe-retreat-2027.html'), 'utf8');
const source = fs.readFileSync(path.join(root, 'retreat-2027.js'), 'utf8');
const dom = new JSDOM(html, {runScripts: 'outside-only', url: 'https://dearpastorswife.org/europe-retreat-2027.html'});
let now = Date.parse('2026-10-17T22:59:59Z');
dom.window.Date.now = () => now;
dom.window.eval(source);
const button = dom.window.document.getElementById('retreat27-checkout');
assert.match(button.textContent, /£250/);
assert.equal(new URL(button.href).searchParams.get('prefilled_promo_code'), 'DPWEARLY2027');
now = Date.parse('2026-10-17T23:00:00Z');
dom.window.dispatchEvent(new dom.window.Event('pageshow'));
assert.match(button.textContent, /£300/);
assert.equal(new URL(button.href).search, '');
assert.match(dom.window.document.getElementById('retreat27-rate-note').textContent, /has closed/);
now = Date.parse('2027-01-31T23:59:00Z');
dom.window.document.dispatchEvent(new dom.window.Event('visibilitychange'));
assert.match(button.textContent, /£300/);
assert.equal(dom.window.document.querySelector('form').id, 'stayInformedForm');
assert.doesNotMatch(html, /Online payment is not open/);
dom.window.close();
console.log('2027 registration: UK cutoff, resumed page, interim price and mailing-list separation passed.');
